"""Shared privacy assertions for exported manifests.

A manifest carries generated metadata -- random IDs, SHA-256 hashes, paths,
timestamps -- whose hex and digits can contain any short substring by
chance. Searching the whole serialized manifest for a fragment like "3361"
is therefore flaky. These checks separate the two:

* the full forms of the test NAM, and its letter prefix (upper-case and not
  hex, so no ID or hash can produce it), are searched for everywhere;
* every *patient-content* string -- anything that is not generated
  metadata -- is run through the app's own NAM detector, which finds a
  health number in any spacing or OCR-confusable spelling.
"""
from __future__ import annotations

import json
from collections.abc import Iterator
from typing import Any

from nam_redactor.locator import canonical_from_text

#: Keys whose values are generated by the app, never patient content.
GENERATED_KEYS = frozenset({
    "row_id", "attempt_id", "review_id", "document_id", "generation_id",
    "sha256", "evidence_sha256", "original_sha256", "fingerprint",
    "path", "evidence_path",
    "generated_at", "approved_at", "reviewed_at", "extracted_at",
    "schema", "prompt_version", "notice", "coordinate_convention",
    "evidence_paths_relative_to",
})

#: The NAM used by the synthetic test documents, in every written form.
TEST_NAM_FORMS = ("HOGP 3361 0615", "HOGP33610615", "33610615", "3361 0615", "HOGP")


def patient_strings(value: Any, key: str | None = None) -> Iterator[str]:
    """Every string in ``value`` that is not generated metadata."""
    if key in GENERATED_KEYS:
        return
    if isinstance(value, dict):
        for k, v in value.items():
            yield from patient_strings(v, k)
    elif isinstance(value, list):
        for item in value:
            yield from patient_strings(item, key)
    elif isinstance(value, str):
        yield value


def assert_no_identifiers(manifest: dict[str, Any], *secrets: str) -> None:
    """No health number and none of ``secrets`` (names, keys, filenames)."""
    text = json.dumps(manifest)
    for form in TEST_NAM_FORMS:
        assert form not in text, f"NAM form {form!r} in manifest"
    for secret in secrets:
        assert secret not in text, f"{secret!r} in manifest"
    for value in patient_strings(manifest):
        assert canonical_from_text(value) is None, f"health number in {value!r}"
